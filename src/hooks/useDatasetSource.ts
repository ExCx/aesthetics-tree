import { useEffect, useState } from 'react';
import type { RefObject } from 'react';
import { normalizeGraphDataset } from '../data/normalizeGraph';
import type {
  NormalizedGraph,
  RawDatasetInput,
  ToastState,
} from '../graph/types';

export interface UseDatasetSourceArgs {
  notify: (message: string, type?: ToastState['type']) => void;
  dirtyRef: RefObject<boolean>;
  /** Lets the orchestrator reset UI-only state after a load. */
  onDatasetLoaded: (graph: NormalizedGraph) => void;
}

export interface DatasetSource {
  rawDataset: RawDatasetInput;
}

const EMPTY_DATASET: RawDatasetInput = { nodes: [], edges: [] };

const DATASET_URLS = [
  './aesthetics_data_tiered.json',
  './aesthetics_data.json',
];

/**
 * Loads the scraper output from `public/` on mount.
 *
 * There is no built-in fallback and no manual upload path: the app is purely
 * data-driven, so `public/aesthetics_data_tiered.json` must be generated by
 * `aesthetics-scraper/` and shipped alongside the app.
 */
export function useDatasetSource({
  notify,
  dirtyRef,
  onDatasetLoaded,
}: UseDatasetSourceArgs): DatasetSource {
  const [rawDataset, setRawDataset] = useState<RawDatasetInput>(EMPTY_DATASET);

  // Silent autoload of /aesthetics_data_tiered.json from public/ on mount (with fallback to /aesthetics_data.json)
  useEffect(() => {
    let cancelled = false;

    const loadFromPublic = async () => {
      for (const url of DATASET_URLS) {
        try {
          const res = await fetch(url);
          if (!res.ok) continue;
          const data = await res.json();
          if (cancelled) return;
          if (data && (Array.isArray(data) || Array.isArray(data.nodes))) {
            setRawDataset(data);
            const norm = normalizeGraphDataset(data);
            onDatasetLoaded(norm);
            dirtyRef.current = true;
            notify(
              `Loaded ${norm.nodes.length.toLocaleString()} aesthetics & ${(
                norm.directedEdges.length + norm.peerEdges.length
              ).toLocaleString()} connections`,
              'success'
            );
            return;
          }
        } catch {
          // Try the next candidate.
        }
      }
      if (!cancelled) {
        notify('Could not load aesthetics data from public/', 'error');
      }
    };

    loadFromPublic();
    return () => {
      cancelled = true;
    };
  }, [dirtyRef, notify, onDatasetLoaded]);

  return { rawDataset };
}
